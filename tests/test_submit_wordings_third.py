def form_line(*fields, answers=F1, consents=None, kept=None):
    return match.match(Form(fields), answers, "Acme", kept=kept, consents=consents, us_job=True)


def asked(label, kind="single", choices=YES_NO, help="", key="question_1", part="company", required=True):
    options = tuple(Choice(text, str(number)) for number, text in enumerate(choices))
    return Field(key, label, kind, required, part, help, options if kind in ("single", "multi") else ())


