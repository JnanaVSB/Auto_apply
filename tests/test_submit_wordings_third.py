TIMES = {
    "": "either",
    " now": "now",
    " currently": "now",
    " in the future": "future",
    " now or in the future": "either",
}
VERBS = ("need", "require")
WHAT = ("sponsorship", "visa sponsorship", "immigration sponsorship", "employment sponsorship", "work sponsorship")
TAILS = ("", " to work in the US", " for employment visa status", " e.g. H-1B")


def needs(now, future, asks):
    if asks != "either":
        return {"yes": "Yes", "no": "No"}[now if asks == "now" else future]
    return "Yes" if "yes" in (now, future) else "No"


@pytest.mark.parametrize("now", ["yes", "no"])
@pytest.mark.parametrize("future", ["yes", "no"])
def test_every_plain_sponsorship_form_reads_the_time_it_asks_about(now, future):
    answers = person(work={"sponsorship_now": now, "sponsorship_future": future})
    for time, asks in TIMES.items():
        for lead in ("Will you", "Do you", "Would you"):
            for verb in VERBS:
                for what in WHAT:
                    for tail in TAILS:
                        label = f"{lead}{time} {verb} {what}{tail}?"
                        found = form_line(asked(label), answers=answers)[0][0]
                        assert record.shown(found) == needs(now, future, asks), label


